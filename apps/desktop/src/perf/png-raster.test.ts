import { expect, test } from 'vitest';
import { exportMatrix } from './png-geometry';
import { photoRasterGeometry, type BitmapToRaw } from './png-raster';

const raw = { width: 4000, height: 3000 };
function apply(matrix: BitmapToRaw, x: number, y: number) {
  const [a, b, c, d, e, f] = matrix;
  return { x: a * x + c * y + e, y: b * x + d * y + f };
}
const rawPixelPoints = [
  [0, 0],
  [3999, 0],
  [3999, 2999],
  [0, 2999],
  [99.5, 2899.5],
  [3899.5, 99.5],
  [745, 1201],
] as const;

test('native EXIF6 oriented bitmap shares 3000x4000 PNG corners and component positions after inverse mapping', () => {
  const raster = photoRasterGeometry(raw, { width: 3000, height: 4000 }, 6);
  const layer = exportMatrix('rot90', raw, 1);
  for (const [x, y] of rawPixelPoints) {
    // Independent zero-based clockwise formula, as observed natural bitmap already has EXIF6.
    const expected = { x: 2999 - y, y: x };
    const bitmapCenter = { x: expected.x + 0.5, y: expected.y + 0.5 };
    const rawCenter = apply(raster.bitmapToRaw, bitmapCenter.x, bitmapCenter.y);
    const photo = apply(layer, rawCenter.x, rawCenter.y);
    const component = apply(layer, x + 0.5, y + 0.5);
    expect({ x: photo.x - 0.5, y: photo.y - 0.5 }).toEqual(expected);
    expect(photo).toEqual(component);
    expect(photo.x).toBeGreaterThanOrEqual(0.5);
    expect(photo.x).toBeLessThanOrEqual(2999.5);
    expect(photo.y).toBeGreaterThanOrEqual(0.5);
    expect(photo.y).toBeLessThanOrEqual(3999.5);
  }
  expect(raster.bitmapCoordinates).toBe('exif6-oriented');
});

test('landscape and EXIF6 raw non-auto-oriented bitmaps preserve independently expected output points', () => {
  for (const exif of [1, 6] as const)
    for (const scale of [1, 0.5]) {
      const raster = photoRasterGeometry(raw, { width: 4000 * scale, height: 3000 * scale }, exif);
      const layer = exportMatrix(exif === 6 ? 'rot90' : 'none', raw, scale);
      for (const [x, y] of rawPixelPoints) {
        const bitmapCenter = { x: (x + 0.5) * scale, y: (y + 0.5) * scale };
        const rawCenter = apply(raster.bitmapToRaw, bitmapCenter.x, bitmapCenter.y);
        const photo = apply(layer, rawCenter.x, rawCenter.y);
        const expected =
          exif === 6
            ? { x: (3000 - y - 0.5) * scale - 0.5, y: (x + 0.5) * scale - 0.5 }
            : { x: (x + 0.5) * scale - 0.5, y: (y + 0.5) * scale - 0.5 };
        expect({ x: photo.x - 0.5, y: photo.y - 0.5 }).toEqual(expected);
      }
      expect(raster.bitmapCoordinates).toBe('raw');
    }
});

test('scaled oriented bitmap keeps known portrait marker centers together with layer centers', () => {
  const raster = photoRasterGeometry(raw, { width: 1500, height: 2000 }, 6);
  const layer = exportMatrix('rot90', raw, 0.5);
  // Hand-derived 50%-resolution visible pixel centers, not generated by either matrix.
  for (const [bitmapX, bitmapY, rawX, rawY] of [
    [50, 50, 100, 2900],
    [1450, 1950, 3900, 100],
  ]) {
    const rawCenter = apply(raster.bitmapToRaw, bitmapX!, bitmapY!);
    expect(rawCenter).toEqual({ x: rawX, y: rawY });
    const png = apply(layer, rawCenter.x, rawCenter.y);
    expect(png).toEqual({ x: bitmapX, y: bitmapY });
    expect(png).toEqual(apply(layer, rawX!, rawY!));
  }
});
